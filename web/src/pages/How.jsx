/** "On this page": jumps to a section and marks the one being read. */
function Toc() {
  const [on, setOn] = useState(TOC[0][0]);
  useEffect(() => {
    if (location.hash) document.getElementById(location.hash.slice(1))?.scrollIntoView();
    // The section being read is the last one whose heading has passed just under the top bar.
    const pick = () => {
      let cur = TOC[0][0];
      for (const [id] of TOC) { const el = document.getElementById(id); if (el && el.getBoundingClientRect().top <= 140) cur = id; }
      setOn(cur);
    };
    pick();
    addEventListener('scroll', pick, { passive: true });
    return () => { removeEventListener('scroll', pick); };
  }, []);
  const go = (e, id) => {
    e.preventDefault();
    document.getElementById(id)?.scrollIntoView({ behavior: 'smooth' });
    history.replaceState(null, '', `#${id}`);
  };
  return (
    <aside className="toc">
      <div className="toc-label">On this page</div>
      <nav>{TOC.map(([id, label]) => <a key={id} href={`#${id}`} className={on === id ? 'on' : ''} onClick={(e) => go(e, id)}>{label}</a>)}</nav>
      <div className="card toc-next">
        <b>Next steps</b>
        <Link href="/launch">Launch <IArrow size={12} /></Link>
        <Link href="/explore">Explore coins <IArrow size={12} /></Link>
        <a href="/terms">Terms</a>
        <a href="/privacy">Privacy</a>
      </div>
    </aside>
  );
}

